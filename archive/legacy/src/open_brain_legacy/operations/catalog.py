JOBS_BY_ID = MappingProxyType({job.id: job for job in JOB_CATALOG})


def get_job(job_id: str) -> JobSpec:
    try:
        return JOBS_BY_ID[job_id]
    except (KeyError, TypeError):
        raise KeyError("unknown operations job") from None
