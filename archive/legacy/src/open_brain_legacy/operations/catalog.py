def _interval(seconds: int, *, run_at_load: bool = False) -> TriggerSpec:
    return TriggerSpec(
        kind=TriggerKind.INTERVAL,
        interval_seconds=seconds,
        run_at_load=run_at_load,
    )


def _calendar(hour: int, minute: int, *, weekday: int | None = None) -> TriggerSpec:
    return TriggerSpec(
        kind=TriggerKind.CALENDAR,
        hour=hour,
        minute=minute,
        weekday=weekday,
    )


def _keepalive() -> TriggerSpec:
    return TriggerSpec(kind=TriggerKind.KEEPALIVE, run_at_load=True)


def _calendar_interval(seconds: int) -> TriggerSpec:
    return TriggerSpec(
        kind=TriggerKind.CALENDAR_INTERVAL,
        interval_seconds=seconds,
        persistent=True,
    )


def _job(
    number: int,
    command: tuple[str, ...],
    *,
    host_role: HostRole,
    trigger: TriggerSpec,
    writer_scope: WriterScope,
    lock_scope: LockScope,
    timeout_seconds: int,
    retry: RetryPolicy = RetryPolicy.NEVER,
    env_refs: tuple[str, ...] = (),
    output_policy: OutputPolicy = OutputPolicy.METADATA_ONLY,
    state: JobState = JobState.ENABLED,
) -> JobSpec:
    job_id = f"JOB-{number:03d}"
    deployment_target, allowed_platforms = EXPECTED_JOB_DEPLOYMENTS[job_id]
    return JobSpec(
        id=job_id,
        command=command,
        deployment_target=deployment_target,
        allowed_platforms=allowed_platforms,
        host_role=host_role,
        trigger=trigger,
        writer_scope=writer_scope,
        lock_scope=lock_scope,
        timeout_seconds=timeout_seconds,
        retry=retry,
        env_refs=env_refs,
        output_policy=output_policy,
        state=state,
    )


