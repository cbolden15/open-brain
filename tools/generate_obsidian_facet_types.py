"""Generate the plugin's DTO types from the authoritative Stage 1 closed schema."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "packages/engine/src/open_brain_engine/engine/facet_schema.json"
TARGET = ROOT / "packages/obsidian-plugin/src/facet-types.ts"


def alias(name: str) -> str:
    return "Wire_" + re.sub(r"[^a-zA-Z0-9_]", "_", name)


def render(rule: dict[str, Any]) -> str:
    if "ref" in rule:
        return alias(rule["ref"])
    if "anyOf" in rule:
        return " | ".join(render(option) for option in rule["anyOf"])
    if "enum" in rule:
        return " | ".join(json.dumps(item) for item in rule["enum"])
    kind = rule["type"]
    if kind == "object":
        fields = [
            f"readonly {json.dumps(key)}{'?' if key in rule['optional'] else ''}: {render(item)}"
            for key, item in rule["properties"].items()
        ]
        return "{ " + "; ".join(fields) + " }"
    if kind == "array":
        return f"ReadonlyArray<{render(rule['items'])}>"
    return {"integer": "number", "string": "string", "boolean": "boolean", "null": "null"}[kind]


def generated() -> str:
    schema = json.loads(SOURCE.read_text())
    lines = [
        "// Generated by tools/generate_obsidian_facet_types.py. Do not hand-edit.",
        f"// Source contract: {schema['contract_revision']}.",
    ]
    for name, rule in schema["definitions"].items():
        lines.append(f"export type {alias(name)} = {render(rule)};")
    for direction in ("Request", "Response"):
        lines.append(f"export interface Facet{direction}Map {{")
        for operation in schema["operations"]:
            response_type = alias(operation + "." + direction.lower())
            lines.append(f"  {json.dumps(operation)}: {response_type};")
        lines.append("}")
    lines.append("export type FacetOperation = keyof FacetRequestMap;")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generated()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != content:
            raise SystemExit("Obsidian facet types differ from the Stage 1 schema")
    else:
        TARGET.write_text(content)
